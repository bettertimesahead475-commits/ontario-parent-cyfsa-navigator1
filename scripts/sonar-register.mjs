// Builds engineering/sonar/FINDINGS.md from SonarCloud's public API data (read-only; the project is public).
// Usage: node scripts/sonar-register.mjs <download-dir> <main-sha> <active-sha>
//   <download-dir> holds pr115-issues-1.json and main-issues-{1,2,3}.json from api/issues/search.
// Main-branch issues are kept only when their file and flagged line still exist at <active-sha>.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const [dir, mainSha, activeSha] = process.argv.slice(2);
if (!dir || !mainSha || !activeSha) throw new Error('usage: sonar-register.mjs <dir> <main-sha> <active-sha>');
const read = (f) => { try { return JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).issues || []; } catch { return []; } };
const cache = new Map();
const lines = (sha, file) => {
  const key = `${sha}:${file}`;
  if (!cache.has(key)) {
    try { cache.set(key, execFileSync('git', ['show', key], { encoding: 'utf8', maxBuffer: 1e8, stdio: ['ignore', 'pipe', 'ignore'] }).split(/\r?\n/)); }
    catch { cache.set(key, null); }
  }
  return cache.get(key);
};
const fileOf = (i) => i.component.split(':').slice(1).join(':');
const owner = (f) => f.startsWith('src/components/admin/') || f === 'src/utils/api.ts' ? 'Claude'
  : f.startsWith('src/') || f.startsWith('public/') ? 'Antigravity'
  : 'Claude';
const exposure = (f) => /^(functions|workers)\//.test(f) || f.startsWith('shared/') || f.startsWith('src/') || f.startsWith('public/') ? 'production'
  : f === 'api/_server.ts' ? 'legacy Express (not deployed)'
  : /^api\/services\//.test(f) ? 'shared services (bundled where imported)'
  : f.startsWith('.github/') ? 'CI'
  : f.startsWith('scripts/') ? 'developer scripts'
  : f.startsWith('supabase/') ? 'database (pending)'
  : 'test support';

const pr = read('pr115-issues-1.json').map((i) => ({ ...i, src: 'PR#115' }));
const main = [1, 2, 3].flatMap((p) => read(`main-issues-${p}.json`)).map((i) => ({ ...i, src: 'main' })).filter((i) => {
  const now = lines(activeSha, fileOf(i));
  if (!now) return false;
  const before = lines(mainSha, fileOf(i));
  const flagged = i.textRange && before ? before[i.textRange.startLine - 1] : null;
  return flagged == null || now.some((l) => l.trim() === flagged.trim());
});
const all = [...pr, ...main];
const rank = { BLOCKER: 0, CRITICAL: 1, MAJOR: 2, MINOR: 3, INFO: 4 };
const typeRank = { VULNERABILITY: 0, BUG: 1, CODE_SMELL: 2 };
all.sort((a, b) => typeRank[a.type] - typeRank[b.type] || rank[a.severity] - rank[b.severity] || fileOf(a).localeCompare(fileOf(b)));

const out = [
  '# SonarCloud findings in the active code (generated)',
  '',
  `Generated by \`scripts/sonar-register.mjs\` from SonarCloud data. Active code: \`${activeSha}\` (PR #115 = production branch).`,
  `Main-branch issues are included only where the flagged line still exists at \`${activeSha}\`. Status is maintained in`,
  '`engineering/SONARQUBE_REGISTER.md` (this table is the inventory).',
  '',
  `Total: ${all.length} (PR #115: ${pr.length}; main, still present: ${main.length})`,
  '',
  '| # | Source | Type | Severity | Rule | Location | Exposure | Owner | Message |',
  '|---|---|---|---|---|---|---|---|---|',
  ...all.map((i, n) => `| ${n + 1} | ${i.src} | ${i.type} | ${i.severity} | ${i.rule} | ${fileOf(i)}:${i.textRange?.startLine ?? '-'} | ${exposure(fileOf(i))} | ${owner(fileOf(i))} | ${i.message.replace(/\|/g, '/').slice(0, 140)} |`),
];
fs.mkdirSync('engineering/sonar', { recursive: true });
fs.writeFileSync('engineering/sonar/FINDINGS.md', out.join('\n') + '\n');
console.log(JSON.stringify({ total: all.length, pr: pr.length, main: main.length }));

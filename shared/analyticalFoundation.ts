/**
 * Source-grounded analytical foundation: the facts a completed analysis established from the document, kept separate from
 * the interpretations that depend on the mode (Basic or Forensic). Pure: no model call, no storage.
 *
 * Kept (mode-independent, checked against the document text):
 *   - quotations whose verification the analyzer recorded and that appear in the document;
 *   - chronology dates that are valid calendar days and are found in the document;
 *   - parties named in the document metadata, when the name appears in the document;
 *   - allegations: the quoted passage, where it is, and how the analyzer classified the evidence.
 *
 * Excluded (mode-specific interpretation, regenerated by each mode): explanations, severity, legal references,
 * parent action steps, lawyer briefs, threshold verdicts, verification verdicts and file summaries.
 */

export const FOUNDATION_SCHEMA_VERSION = 1;

export interface FoundationQuote {
  quote: string;
  locator: string;
  /** Analyzer-recorded classification of the evidence (for example DIRECT, HEARSAY). Not an interpretation of guilt. */
  evidenceClassification: string | null;
}

export interface FoundationDate {
  isoDate: string;
  dateAsWritten: string;
  event: string;
  locator: string;
}

export interface FoundationParty {
  role: string;
  name: string;
}

export interface AnalyticalFoundation {
  schemaVersion: number;
  documentFingerprint: string;
  sourceJobId: string;
  sourceMode: 'fast' | 'full';
  quotes: FoundationQuote[];
  dates: FoundationDate[];
  parties: FoundationParty[];
  /** Names of interpretation fields deliberately not carried forward. Recorded so a reader knows what was left out. */
  excludedInterpretations: string[];
}

const EXCLUDED = [
  'redFlags.explanation',
  'redFlags.severity',
  'redFlags.category',
  'redFlags.parentActionStep',
  'redFlags.legalReference',
  'thresholdAnalysis',
  'forensicVerification',
  'guidance',
  'fileSummary',
];

function normalise(text: string): string {
  return text.replace(/\s+/g, ' ').trim().toLowerCase();
}

/** A quotation counts only if it appears in the document text. The analyzer's own flag is not enough on its own. */
export function quoteIsInDocument(quote: string, documentText: string): boolean {
  const q = normalise(quote);
  return q.length >= 8 && normalise(documentText).includes(q);
}

export function extractFoundation(args: {
  report: Record<string, any>;
  documentText: string;
  documentFingerprint: string;
  sourceJobId: string;
  sourceMode: 'fast' | 'full';
}): AnalyticalFoundation {
  const { report, documentText } = args;

  const quotes: FoundationQuote[] = [];
  for (const f of Array.isArray(report.redFlags) ? report.redFlags : []) {
    const quote = typeof f?.phraseDetected === 'string' ? f.phraseDetected : '';
    if (f?.quoteVerified === true && quoteIsInDocument(quote, documentText)) {
      quotes.push({
        quote,
        locator: typeof f.locationInDocument === 'string' ? f.locationInDocument : '',
        evidenceClassification: typeof f.evidenceClassification === 'string' ? f.evidenceClassification : null,
      });
    }
  }

  const dates: FoundationDate[] = [];
  for (const row of Array.isArray(report.chronology) ? report.chronology : []) {
    const grounding = row?.dateGrounding;
    if (grounding?.status === 'GROUNDED' && typeof grounding.isoDate === 'string' && typeof row.date === 'string') {
      if (quoteIsInDocument(row.date, documentText) || documentText.includes(row.date)) {
        dates.push({
          isoDate: grounding.isoDate,
          dateAsWritten: row.date,
          event: typeof row.event === 'string' ? row.event : '',
          locator: typeof row.locationInDocument === 'string' ? row.locationInDocument : '',
        });
      }
    }
  }

  const parties: FoundationParty[] = [];
  const metadata = report.metadata && typeof report.metadata === 'object' ? report.metadata : {};
  for (const [role, value] of Object.entries(metadata)) {
    if (typeof value === 'string' && value.trim().length >= 2 && documentText.includes(value.trim())) {
      parties.push({ role, name: value.trim() });
    }
  }

  return {
    schemaVersion: FOUNDATION_SCHEMA_VERSION,
    documentFingerprint: args.documentFingerprint,
    sourceJobId: args.sourceJobId,
    sourceMode: args.sourceMode,
    quotes,
    dates,
    parties,
    excludedInterpretations: [...EXCLUDED],
  };
}

/**
 * Prompt block that carries the foundation into a Forensic request. It is presented as material to build on AND to
 * challenge: the model may dispute any item where its own reading of the source disagrees, and must say so.
 */
export function foundationPromptBlock(f: AnalyticalFoundation): string {
  const lines: string[] = [
    'SOURCE FOUNDATION (established earlier from this same document; each item was checked against the text):',
  ];
  for (const q of f.quotes) lines.push(`- Quotation (${q.locator || 'location not given'}): "${q.quote}"`);
  for (const d of f.dates) lines.push(`- Date ${d.isoDate} (written "${d.dateAsWritten}"): ${d.event}`);
  for (const p of f.parties) lines.push(`- ${p.role}: ${p.name}`);
  lines.push(
    'Use this as a starting point. You may challenge or extend any item if the document shows it is wrong or incomplete, ' +
      'and you must then say so in your own findings. Interpretations, severities and legal conclusions are yours to form.'
  );
  return lines.join('\n');
}

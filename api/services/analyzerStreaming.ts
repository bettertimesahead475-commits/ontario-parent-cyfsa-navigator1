/**
 * CYFSA Navigator — Server-Sent Events (SSE) Streaming & Durable Job Store
 *
 * Provides real-time server-backed progress streaming and resilient job recovery
 * without fake percentages or simulated AI output.
 */

import { Response } from "express";

export type AnalysisStage =
  | "uploading"
  | "extracting"
  | "verifying_access"
  | "reviewing_evidence"
  | "building_chronology"
  | "identifying_legal_issues"
  | "verifying_findings"
  | "preparing_report"
  | "complete";

export interface StageInfo {
  stage: AnalysisStage;
  message: string;
  percent: number;
}

export const STAGE_DEFINITIONS: Record<AnalysisStage, { message: string; percent: number }> = {
  uploading: {
    message: "Uploading document and verifying integrity...",
    percent: 10,
  },
  extracting: {
    message: "Extracting document text and verifying structure...",
    percent: 20,
  },
  verifying_access: {
    message: "Verifying account access and analysis entitlements...",
    percent: 30,
  },
  reviewing_evidence: {
    message: "Reviewing evidence items and calculating Evidence Strength Index...",
    percent: 45,
  },
  building_chronology: {
    message: "Extracting document metadata, timeline anchors, and core facts...",
    percent: 60,
  },
  identifying_legal_issues: {
    message: "Analyzing CYFSA statutory thresholds and procedural timeline rules...",
    percent: 75,
  },
  verifying_findings: {
    message: "Conducting Claude Opus forensic verification on high-impact findings...",
    percent: 88,
  },
  preparing_report: {
    message: "Validating direct quotes and assembling final comprehensive audit...",
    percent: 95,
  },
  complete: {
    message: "Analysis verified and complete.",
    percent: 100,
  },
};

export interface AnalysisJob {
  jobId: string;
  uid: string | null;
  mode: "fast" | "full";
  status: "pending" | "analyzing" | "completed" | "failed";
  currentStage: AnalysisStage;
  percent: number;
  report?: any;
  error?: {
    code: string;
    message: string;
    statusCode: number;
    retryable: boolean;
  };
  /** Report sections that already passed validation, keyed by section name (partial progress). */
  sections?: Record<string, any>;
  sectionsTotal?: number;
  message?: string;
  createdAt: number;
  updatedAt: number;
}

/**
 * Job ids double as Supabase Storage object names, so only the client format generated by the
 * analyzer ("req_<epoch ms>_<random>") is accepted; anything else gets a server-generated id.
 */
export function isValidAnalysisJobId(id: unknown): id is string {
  return typeof id === "string" && /^req_\d{10,16}_[a-z0-9]{4,24}$/i.test(id);
}

export function generateAnalysisJobId(): string {
  return `req_${Date.now()}_${Math.random().toString(36).substring(2, 11)}`;
}

import { getSupabase } from "./access.js";
import { AnalyzerError } from "./analyzerErrors.js";

const jobStore = new Map<string, AnalysisJob>();
/**
 * Jobs that could not be claimed exclusively in Storage. They run to completion in memory and the report is returned
 * to the client, but nothing is ever written to Storage for them. Every later write is an unconditional upsert, so
 * letting one through after a failed claim could overwrite another account's record if Storage recovers mid-run.
 */
const memoryOnlyJobs = new Set<string>();
const JOB_RETENTION_MS = 24 * 60 * 60 * 1000; // 24 hours
const BUCKET_NAME = "analysis_jobs";
let bucketChecked = false;

function safeGetSupabase() {
  try {
    return getSupabase();
  } catch {
    return null;
  }
}

async function ensureBucket(): Promise<boolean> {
  if (bucketChecked) return true;
  const db = safeGetSupabase();
  if (!db) return false;
  try {
    const { data: buckets } = await db.storage.listBuckets();
    if (buckets) {
      const existing = buckets.find((b: any) => b.name === BUCKET_NAME);
      if (existing) {
        if (existing.public) {
          await db.storage.updateBucket(BUCKET_NAME, { public: false });
        }
        bucketChecked = true;
        return true;
      }
    }
    const { error: cErr } = await db.storage.createBucket(BUCKET_NAME, { public: false });
    if (!cErr || cErr.message?.includes("already exists")) {
      bucketChecked = true;
      return true;
    }
  } catch {
    // fallback
  }
  return false;
}

export async function persistJobToStorage(job: AnalysisJob): Promise<void> {
  if (memoryOnlyJobs.has(job.jobId)) return;
  const db = safeGetSupabase();
  if (!db) return;
  try {
    const hasBucket = await ensureBucket();
    if (hasBucket) {
      await db.storage
        .from(BUCKET_NAME)
        .upload(`${job.jobId}.json`, JSON.stringify(job), {
          upsert: true,
          contentType: "application/json",
        });
    }
  } catch {
    // ignore storage upload failures, memory state remains intact
  }
}

/** Uploads a job record and throws unless it is really in Storage. persistJobToStorage ignores failures instead. */
async function uploadJobStrict(job: AnalysisJob): Promise<void> {
  if (memoryOnlyJobs.has(job.jobId)) throw new Error("Job is memory-only: it could not be claimed in Storage");
  const db = safeGetSupabase();
  if (!db) throw new Error("Storage is not configured");
  const hasBucket = await ensureBucket();
  if (!hasBucket) throw new Error("Job storage bucket is unavailable");
  const { error } = await db.storage
    .from(BUCKET_NAME)
    .upload(`${job.jobId}.json`, JSON.stringify(job), { upsert: true, contentType: "application/json" });
  if (error) throw new Error(`Job upload failed: ${error.message}`);
}

/**
 * Stores a finished job under a new id and throws unless the record is really in Storage. For callers that must
 * not report a job as available when it was not saved.
 */
export async function storeCompletedJobStrict(params: {
  jobId: string;
  uid: string;
  mode: "fast" | "full";
  report: unknown;
}): Promise<void> {
  const now = Date.now();
  const job = {
    jobId: params.jobId,
    uid: params.uid,
    mode: params.mode,
    status: "completed",
    currentStage: "complete",
    percent: 100,
    report: params.report,
    createdAt: now,
    updatedAt: now,
  } as AnalysisJob;
  await uploadJobStrict(job);
  // Same as completeAnalysisJob: this instance can serve the job without reading it back from Storage.
  jobStore.set(job.jobId, job);
}

/**
 * Completes an existing in-memory job and throws unless the completed record is really in Storage. The job is
 * completed in memory either way, so the running request can still answer from it.
 */
export async function completeAnalysisJobStrict(jobId: string, report: any): Promise<void> {
  completeAnalysisJob(jobId, report);
  const job = jobStore.get(jobId);
  if (!job) throw new Error("Job is not registered");
  await uploadJobStrict(job);
}

export async function fetchJobFromStorage(jobId: string): Promise<AnalysisJob | null> {
  const db = safeGetSupabase();
  if (!db) return null;
  try {
    const hasBucket = await ensureBucket();
    if (!hasBucket) return null;
    const { data, error } = await db.storage.from(BUCKET_NAME).download(`${jobId}.json`);
    if (data && !error) {
      const text = await data.text();
      const job = JSON.parse(text) as AnalysisJob;
      const local = jobStore.get(jobId);
      if (local) {
        // This instance's own live copy is newer than Storage, and Storage cannot be trusted to overrule it.
        if (memoryOnlyJobs.has(jobId) && local.uid === job.uid) return local;
        // Another account's record is reported as it is, but never adopted over the job held here: adopting it would
        // let this instance's running analysis complete into an object owned by someone else.
        if (local.uid !== job.uid) return job;
      }
      jobStore.set(job.jobId, job);
      return job;
    }
  } catch {
    // fallback
  }
  return null;
}

type NewJobParams = {
  jobId: string;
  uid: string | null;
  mode: "fast" | "full";
  currentStage?: AnalysisStage;
  percent?: number;
};

/** Builds a new job record and registers it in this instance's memory. Does not touch Storage. */
function registerNewJob(params: NewJobParams): AnalysisJob {
  // Prune expired jobs
  const now = Date.now();
  if (jobStore.size > 200) {
    for (const [id, job] of jobStore.entries()) {
      if (now - job.createdAt > JOB_RETENTION_MS) {
        jobStore.delete(id);
        memoryOnlyJobs.delete(id);
      }
    }
  }

  const initialStage = params.currentStage || "verifying_access";
  const initialPercent = params.percent ?? (STAGE_DEFINITIONS[initialStage]?.percent || 30);

  const job: AnalysisJob = {
    jobId: params.jobId,
    uid: params.uid,
    mode: params.mode,
    status: "analyzing",
    currentStage: initialStage,
    percent: initialPercent,
    createdAt: now,
    updatedAt: now,
  };
  jobStore.set(params.jobId, job);
  return job;
}

export function createAnalysisJob(params: NewJobParams): AnalysisJob {
  const job = registerNewJob(params);
  // Asynchronously persist initial job record
  persistJobToStorage(job).catch(() => {});
  return job;
}

const conflict = () =>
  new AnalyzerError("ANALYSIS_ID_CONFLICT", 409, "This analysis id is already in use. Please start a new analysis.", false);

/** The id exists but its owner cannot be established right now. Retryable: the client can simply try again. */
const ownerUnverifiable = () =>
  new AnalyzerError("ANALYSIS_PERSISTENCE_FAILED", 503, "We couldn't verify this analysis right now. Please try again in a moment.", true);

const isAlreadyExists = (error: any): boolean =>
  String(error?.statusCode) === "409" || /already exists|duplicate/i.test(String(error?.message ?? ""));

type StoredRecord = { status: "ok"; job: AnalysisJob } | { status: "unreadable" } | { status: "corrupt" };

/** Reads an existing job record and says plainly whether the read worked. A failed read is not "no owner". */
async function readStoredRecord(jobId: string): Promise<StoredRecord> {
  const db = safeGetSupabase();
  if (!db) return { status: "unreadable" };
  try {
    const { data, error } = await db.storage.from(BUCKET_NAME).download(`${jobId}.json`);
    if (error || !data) return { status: "unreadable" };
    const text = await data.text();
    try {
      const job = JSON.parse(text) as AnalysisJob;
      return job && typeof job === "object" && !Array.isArray(job) ? { status: "ok", job } : { status: "corrupt" };
    } catch {
      return { status: "corrupt" }; // the record was read, and it is not a job record
    }
  } catch {
    return { status: "unreadable" };
  }
}

/**
 * Creates a job record for the caller, and refuses to take over a job that belongs to someone else.
 *
 * The first write is an exclusive create (upsert: false), so two server instances racing on one id cannot both
 * create it: the loser finds the record and reads its owner. It is refused (409) unless it is the same account.
 * If the owner cannot be read the claim fails closed with a retryable 503. A record owned by the same account (a
 * retry of a failed or stale analysis) is replaced.
 *
 * If the exclusive claim cannot be made at all (Storage unconfigured or unreachable, or any other Storage error),
 * the job is kept in memory only and never written to Storage. The analysis still completes and the report is
 * returned to the client, so availability is kept, but no later write can overwrite another account's record.
 */
export async function claimAnalysisJobDurable(params: NewJobParams): Promise<AnalysisJob> {
  const refuseIfOwnedByAnother = () => {
    const current = jobStore.get(params.jobId);
    if (current?.uid && current.uid !== params.uid) throw conflict();
  };
  refuseIfOwnedByAnother();

  const memoryOnly = (job: AnalysisJob): AnalysisJob => {
    memoryOnlyJobs.add(job.jobId);
    return job;
  };

  const db = safeGetSupabase();
  const hasBucket = db ? await ensureBucket() : false;
  // Another request may have registered this id while the bucket check was awaiting. Check again, and register, with
  // nothing awaited in between, so two accounts cannot both register the same id on this instance.
  refuseIfOwnedByAnother();
  const inMemory = jobStore.get(params.jobId); // same account's earlier entry, if any
  memoryOnlyJobs.delete(params.jobId); // this run decides afresh
  if (!db || !hasBucket) return memoryOnly(registerNewJob(params));

  const job = registerNewJob(params);
  let result: { error: any } | null;
  try {
    result = await db.storage
      .from(BUCKET_NAME)
      .upload(`${job.jobId}.json`, JSON.stringify(job), { upsert: false, contentType: "application/json" });
  } catch {
    return memoryOnly(job); // network failure: no claim was made
  }
  if (!result?.error) return job; // claimed exclusively
  if (!isAlreadyExists(result.error)) return memoryOnly(job); // any other Storage error: no claim was made

  // Someone created this id first. Only the same account may continue with it. Remove only the entry this request
  // registered: the id may by now hold another request's job.
  if (jobStore.get(job.jobId) === job) {
    jobStore.delete(job.jobId);
    if (inMemory) jobStore.set(job.jobId, inMemory);
  }
  const record = await readStoredRecord(job.jobId);
  if (record.status === "unreadable") throw ownerUnverifiable(); // transient: the same request can simply be retried
  // A corrupt or ownerless record has no owner who could claim it back. Refuse, as the route's pre-check does, so the
  // client starts a new analysis instead of retrying a record that will never become readable.
  if (record.status === "corrupt" || !record.job.uid || record.job.uid !== params.uid) throw conflict();
  return createAnalysisJobDurable(params);
}

export async function createAnalysisJobDurable(params: {
  jobId: string;
  uid: string | null;
  mode: "fast" | "full";
  currentStage?: AnalysisStage;
  percent?: number;
}): Promise<AnalysisJob> {
  const job = createAnalysisJob(params);
  try {
    await persistJobToStorage(job);
  } catch {}
  return job;
}

export function getAnalysisJob(jobId: string): AnalysisJob | null {
  return jobStore.get(jobId) || null;
}

export async function getAnalysisJobDurable(jobId: string): Promise<AnalysisJob | null> {
  const local = jobStore.get(jobId);
  if (local && (local.status === "completed" || local.status === "failed")) {
    return local;
  }
  const fromStorage = await fetchJobFromStorage(jobId);
  return fromStorage || local || null;
}

export function updateAnalysisJobStage(jobId: string, stage: AnalysisStage): void {
  const job = jobStore.get(jobId);
  if (job) {
    job.currentStage = stage;
    job.percent = STAGE_DEFINITIONS[stage]?.percent ?? job.percent;
    job.updatedAt = Date.now();
  }
}

export function completeAnalysisJob(jobId: string, report: any): void {
  const job = jobStore.get(jobId);
  if (job) {
    job.status = "completed";
    job.currentStage = "complete";
    job.percent = 100;
    job.report = report;
    job.updatedAt = Date.now();
    persistJobToStorage(job).catch(() => {});
  }
}

/**
 * Durable variants: the route awaits these so the job record is in Storage before the response
 * ends. A serverless instance can be frozen as soon as the response is sent, so a fire-and-forget
 * upload of the final state could be lost - and recovery after a refresh depends on it.
 */
export async function completeAnalysisJobDurable(jobId: string, report: any): Promise<void> {
  completeAnalysisJob(jobId, report);
  const job = jobStore.get(jobId);
  if (job) await persistJobToStorage(job);
}

export async function failAnalysisJobDurable(
  jobId: string,
  error: { code: string; message: string; statusCode: number; retryable: boolean }
): Promise<void> {
  failAnalysisJob(jobId, error);
  const job = jobStore.get(jobId);
  if (job) await persistJobToStorage(job);
}

/** Records real progress (no invented percent): the stage plus a percent derived from completed work. */
export function updateAnalysisJobProgress(jobId: string, stage: AnalysisStage, percent: number, message?: string): void {
  const job = jobStore.get(jobId);
  if (job) {
    job.currentStage = stage;
    job.percent = Math.max(job.percent, Math.min(99, Math.round(percent)));
    if (message) job.message = message;
    job.updatedAt = Date.now();
  }
}

/** Stores a validated section on the job and persists it, so a reloaded page can see partial work. */
export async function recordAnalysisJobSection(
  jobId: string,
  section: string,
  data: any,
  progress: { stage: AnalysisStage; percent: number; message: string; total: number }
): Promise<void> {
  const job = jobStore.get(jobId);
  if (!job) return;
  job.sections = { ...(job.sections || {}), [section]: data };
  job.sectionsTotal = progress.total;
  updateAnalysisJobProgress(jobId, progress.stage, progress.percent, progress.message);
  await persistJobToStorage(job);
}

export function failAnalysisJob(
  jobId: string,
  error: { code: string; message: string; statusCode: number; retryable: boolean }
): void {
  const job = jobStore.get(jobId);
  if (job) {
    job.status = "failed";
    job.error = error;
    job.updatedAt = Date.now();
    persistJobToStorage(job).catch(() => {});
  }
}

export class SseStreamEmitter {
  private res: Response;
  private jobId: string;
  private heartbeatInterval: NodeJS.Timeout | null = null;
  private isClosed = false;

  constructor(res: Response, jobId: string) {
    this.res = res;
    this.jobId = jobId;

    // Set SSE HTTP headers
    this.res.setHeader("Content-Type", "text/event-stream; charset=utf-8");
    this.res.setHeader("Cache-Control", "no-cache, no-transform");
    this.res.setHeader("Connection", "keep-alive");
    this.res.setHeader("X-Accel-Buffering", "no");

    // Flush headers immediately if available
    if (typeof (this.res as any).flushHeaders === "function") {
      (this.res as any).flushHeaders();
    }

    // When running under a real server/proxy with flush support, send immediate 2KB comment padding
    // to bypass edge reverse-proxy buffering (e.g. Cloudflare, AWS CloudFront, Vercel)
    if (typeof (this.res as any).flush === "function") {
      try {
        this.res.write(": " + " ".repeat(2048) + "\n\n");
        (this.res as any).flush();
      } catch {}
    }

    // Start keep-alive heartbeat every 5s to keep proxy connections open
    this.heartbeatInterval = setInterval(() => {
      if (!this.isClosed) {
        try {
          this.res.write(": keep-alive\n\n");
          this.flush();
        } catch {}
      }
    }, 5000);

    // Clean up on client disconnect
    this.res.on("close", () => {
      this.close();
    });
  }

  private flush(): void {
    if (typeof (this.res as any).flush === "function") {
      try {
        (this.res as any).flush();
      } catch {}
    }
  }

  /**
   * Emits a stage. `percent` is passed only when it is derived from real completed work (e.g.
   * sections validated so far); otherwise the stage's fixed checkpoint value is used.
   */
  public emitStage(stage: AnalysisStage, customMessage?: string, percent?: number): void {
    if (this.isClosed) return;
    const def = STAGE_DEFINITIONS[stage] || { message: "Processing...", percent: 50 };
    if (typeof percent === "number") {
      updateAnalysisJobProgress(this.jobId, stage, percent, customMessage);
    } else {
      updateAnalysisJobStage(this.jobId, stage);
    }

    const payload = {
      type: "stage",
      jobId: this.jobId,
      stage,
      message: customMessage || def.message,
      percent: typeof percent === "number" ? Math.min(99, Math.round(percent)) : def.percent,
      timestamp: Date.now(),
    };

    this.res.write(`data: ${JSON.stringify(payload)}\n\n`);
    this.flush();
  }

  public emitSection(sectionName: string, data: any): void {
    if (this.isClosed) return;
    const payload = {
      type: "section",
      jobId: this.jobId,
      section: sectionName,
      data,
      timestamp: Date.now(),
    };
    this.res.write(`data: ${JSON.stringify(payload)}\n\n`);
    this.flush();
  }

  public emitComplete(report: any, credits?: any): void {
    if (this.isClosed) return;
    completeAnalysisJob(this.jobId, report);

    const payload = {
      type: "complete",
      jobId: this.jobId,
      stage: "complete",
      percent: 100,
      report,
      credits: credits || null,
      timestamp: Date.now(),
    };
    this.res.write(`data: ${JSON.stringify(payload)}\n\n`);
    this.flush();
    this.close();
  }

  public emitError(error: { code: string; message: string; statusCode: number; retryable: boolean }): void {
    if (this.isClosed) return;
    failAnalysisJob(this.jobId, error);

    const payload = {
      type: "error",
      jobId: this.jobId,
      error: error.message,
      code: error.code,
      statusCode: error.statusCode,
      retryable: error.retryable,
      timestamp: Date.now(),
    };
    this.res.write(`data: ${JSON.stringify(payload)}\n\n`);
    this.flush();
    this.close();
  }

  public close(): void {
    if (this.isClosed) return;
    this.isClosed = true;
    if (this.heartbeatInterval) {
      clearInterval(this.heartbeatInterval);
      this.heartbeatInterval = null;
    }
    try {
      this.res.end();
    } catch {}
  }
}
